export function tr(language: Language, russianText: string): string {
  return language === 'en' ? (english[russianText] ?? russianText) : russianText;
}
export function fmtNumber(language: Language, value: number): string {
  return new Intl.NumberFormat(language === 'en' ? 'en-US' : 'ru-RU', { maximumFractionDigits: 1 }).format(value);
}
export function fmtDate(language: Language, iso: string): string {
  return new Date(`${iso}T12:00:00`).toLocaleDateString(language === 'en' ? 'en-US' : 'ru-RU', { day: 'numeric', month: 'short' });
}
export function fmtMonth(language: Language, date = new Date()): string {
  return date.toLocaleDateString(language === 'en' ? 'en-US' : 'ru-RU', { month: 'long' });
}
